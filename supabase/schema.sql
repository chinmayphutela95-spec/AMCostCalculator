-- AM Cost Calculator — Supabase schema
-- Run once in the Supabase dashboard: SQL Editor → New query → paste → Run.
-- Safe to re-run: every statement is idempotent.
--
-- Access model: the browser never talks to these tables directly. All reads and
-- writes go through the FastAPI backend, which connects as the database owner
-- and enforces sign-in, admin rights and project ownership. Row Level Security
-- is enabled with NO policies, so the public (publishable) API key that ships in
-- the frontend cannot read or write any of this data via Supabase's REST API.

-- ── Users ───────────────────────────────────────────────────────────────────
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  email       text not null default '',
  is_admin    boolean not null default false,   -- admins manage machines & materials
  created_at  timestamptz not null default now()
);

-- Create a profile whenever a user is added (Authentication → Users → Add user)
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, coalesce(new.email, ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Profiles for users that existed before this script ran
insert into public.profiles (id, email)
select id, coalesce(email, '') from auth.users
on conflict (id) do nothing;

