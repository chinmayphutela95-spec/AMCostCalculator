  build_plate_length          double precision,           -- cm
  build_height                double precision default 25.0,
  build_area                  double precision default 490.87,
  build_rate                  double precision default 10.0,
  num_lasers                  integer default 1,
  recoating_distance_mm       double precision,
  recoating_speed_mm_s        double precision,
  machine_cost                double precision default 500000.0,
  machine_lifetime            double precision default 7.0,
  cost_of_capital             double precision default 0.05,
  infrastructure_pct          double precision default 0.50,
  maintenance_pct             double precision default 0.05,
  uptime                      double precision default 0.80,
  packing_policy              text default '2D',
  packing_fraction            double precision default 0.90,
  recycling_fraction          double precision default 0.90,
  inert_gas_cost              double precision default 20.0,
  consumable_cost_per_build   double precision default 100.0,
  first_build_prep_time       double precision default 3.0,
  subsequent_build_prep_time  double precision default 0.0,
  setup_time_per_build        double precision default 1.0,
  removal_time_per_build      double precision default 1.0,
  warmup_time                 double precision default 1.0,
  cooldown_time               double precision default 2.0,
  support_constant            double precision default 0.11,
  hours_per_day               double precision default 18.0,
  days_per_week               double precision default 5.0,
  fte_supervised              double precision default 0.15,
  fte_build_exchange          double precision default 1.0,
  fte_support_removal         double precision default 1.0,
  salary_engineer             double precision default 70.0,
  salary_operator             double precision default 50.0,
  salary_technician           double precision default 30.0,
  is_custom                   boolean default false,
  notes                       text default '',
  created_at                  timestamptz default now()
);

-- ── Material library ────────────────────────────────────────────────────────
create table if not exists public.materials (
  id                     bigint generated by default as identity primary key,
  name                   text,
  alloy_designation      text default '',
  category               text default 'Steel',
  process_compatibility  text default 'LPBF',
  cost_per_kg            double precision default 50.0,
  density                double precision default 8.0,
  layer_thickness_um     double precision default 40.0,
  build_rate_cm3_hr      double precision default 10.0,
  yield_strength         double precision,
  tensile_strength       double precision,
  elongation             double precision,
  hardness               double precision,
  max_service_temp       double precision,
  is_custom              boolean default false,
  notes                  text default '',
  created_at             timestamptz default now()
);
create index if not exists materials_name_idx on public.materials (name);

-- ── Saved projects (shared with the whole team) ─────────────────────────────
create table if not exists public.projects (
  id                bigint generated by default as identity primary key,
  name              text,
  description       text default '',
  created_at        timestamptz default now(),
  updated_at        timestamptz default now(),
  part_file_name    text,
  inputs_json       text default '{}',
  results_json      text default '{}',
  ai_insights_json  text default '{}',
  part_snapshot     text,                                            -- 3D view for PDF export
  created_by        uuid references auth.users (id) on delete set null,
  created_by_email  text
);
create index if not exists projects_name_idx on public.projects (name);
create index if not exists projects_created_at_idx on public.projects (created_at desc);

-- ── Lock the tables away from the public REST API ───────────────────────────
alter table public.profiles  enable row level security;
alter table public.machines  enable row level security;
alter table public.materials enable row level security;
alter table public.projects  enable row level security;

revoke all on public.profiles, public.machines, public.materials, public.projects from anon, authenticated;
