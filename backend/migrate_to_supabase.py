"""
One-time copy of the local desktop database (metal_am_cost.db) into Supabase.

Copies machines, materials and saved projects, keeping their ids. Run it after
supabase/schema.sql, against an empty database. Two ways:

  Direct (needs outbound access to Postgres ports 5432/6543):
    venv\\Scripts\\python.exe migrate_to_supabase.py --database-url "postgresql://..." --owner-email you@tii.ae

  Via the Supabase SQL Editor (works on networks that block database ports):
    venv\\Scripts\\python.exe migrate_to_supabase.py --sql-out import.sql --owner-email you@tii.ae
    then paste import.sql into Supabase > SQL Editor > Run.

--owner-email  Optional. Marks the imported projects as created by this user
               (they must already exist under Authentication > Users). Without it,
               imported projects have no owner and only admins can delete them.
"""
import argparse
import os
import sqlite3
import sys

from sqlalchemy import Boolean, create_engine, text
from sqlalchemy.exc import OperationalError

import models
from database import BASE_DIR, _sqlalchemy_postgres_url

TABLES = {
    "machines": models.Machine.__table__,
    "materials": models.Material.__table__,
    "projects": models.Project.__table__,
}


def read_local_rows(sqlite_path: str) -> dict:
    """Rows from the local database, limited to columns that exist in Supabase."""
    src = sqlite3.connect(f"file:{sqlite_path}?mode=ro", uri=True)
    src.row_factory = sqlite3.Row
    data = {}
    for name, table in TABLES.items():
        bool_cols = {c.name for c in table.columns if isinstance(c.type, Boolean)}
        rows = []
        for r in src.execute(f"select * from {name} order by id"):
            row = {k: r[k] for k in r.keys() if k in table.columns and k not in ("created_by", "created_by_email")}
            for k in bool_cols & row.keys():
                row[k] = None if row[k] is None else bool(row[k])
            rows.append(row)
        data[name] = rows
    return data


# ── Direct copy over a database connection ────────────────────────────────────

def copy_direct(database_url: str, data: dict, owner_email):
    pg = create_engine(
        _sqlalchemy_postgres_url(database_url),
        connect_args={"prepare_threshold": None, "connect_timeout": 15},
    )
    print("Connecting to Supabase...")
    try:
        pg.connect().close()
    except OperationalError as e:
        sys.exit(
            f"Could not connect to the database:\n  {str(e).strip().splitlines()[0]}\n\n"
            "If you're on a network that blocks database ports (5432/6543), use the SQL Editor route instead:\n"
            "  migrate_to_supabase.py --sql-out import.sql --owner-email you@tii.ae"
        )

    with pg.begin() as conn:   # one transaction: all rows or nothing
        for name in TABLES:
            count = conn.execute(text(f"select count(*) from public.{name}")).scalar()
            if count:
                sys.exit(f"public.{name} already has {count} rows - this script only fills an empty database.")

        owner_id = None
        if owner_email:
            owner_id = conn.execute(
                text("select id from public.profiles where lower(email) = lower(:email)"), {"email": owner_email}
            ).scalar()
            if owner_id is None:
                sys.exit(f"No Supabase user with email {owner_email}. Add them under Authentication > Users first.")

        for name, table in TABLES.items():
            rows = data[name]
            if name == "projects" and owner_id is not None:
                rows = [{**r, "created_by": owner_id, "created_by_email": owner_email} for r in rows]
            if rows:
                conn.execute(table.insert(), rows)
                # Continue new ids after the copied ones
                conn.execute(text(
                    f"select setval(pg_get_serial_sequence('public.{name}', 'id'), (select max(id) from public.{name}))"
                ))
            print(f"  {name:<10} {len(rows):>4} rows copied")
    print("Done.")


# ── SQL file for the Supabase SQL Editor ──────────────────────────────────────

def sql_literal(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v) if v == v and v not in (float("inf"), float("-inf")) else f"'{v}'::float8"
    return "'" + str(v).replace("'", "''") + "'"


def write_sql(path: str, data: dict, owner_email):
    lines = [
        "-- Generated by backend/migrate_to_supabase.py - paste into Supabase > SQL Editor > Run.",
        "-- Copies machines, materials and projects from the local desktop database.",
        "begin;",
        "",
        "do $$ begin",
        "  if exists (select 1 from public.machines) or exists (select 1 from public.materials)",
        "     or exists (select 1 from public.projects) then",
        "    raise exception 'Supabase tables already contain data; this import only fills an empty database.';",
        "  end if;",
    ]
    if owner_email:
        lines += [
            f"  if not exists (select 1 from public.profiles where lower(email) = lower({sql_literal(owner_email)})) then",
            f"    raise exception 'No user {owner_email.replace(chr(39), '')} - add them under Authentication > Users first.';",
            "  end if;",
        ]
    lines += ["end $$;", ""]

    owner_sql = (
        f"(select id from public.profiles where lower(email) = lower({sql_literal(owner_email)}))"
        if owner_email else None
    )
    for name, rows in data.items():
        if not rows:
            continue
        for row in rows:
            cols = list(row.keys())
            vals = [sql_literal(row[c]) for c in cols]
            if name == "projects" and owner_sql:
                cols += ["created_by", "created_by_email"]
                vals += [owner_sql, sql_literal(owner_email)]
            lines.append(f"insert into public.{name} ({', '.join(cols)}) values ({', '.join(vals)});")
        lines.append(
            f"select setval(pg_get_serial_sequence('public.{name}', 'id'), (select max(id) from public.{name}));"
        )
        lines.append("")

    lines += [
        "commit;",
        "",
        "select 'machines' as table_name, count(*) from public.machines",
        "union all select 'materials', count(*) from public.materials",
        "union all select 'projects', count(*) from public.projects;",
        "",
    ]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    for name, rows in data.items():
        print(f"  {name:<10} {len(rows):>4} rows")
    print(f"Wrote {path} ({os.path.getsize(path) // 1024} KB). Paste it into Supabase > SQL Editor > Run.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--database-url", help="Supabase connection string (with password)")
    target.add_argument("--sql-out", metavar="FILE", help="write a SQL file for the Supabase SQL Editor instead")
    parser.add_argument("--sqlite", default=os.path.join(BASE_DIR, "metal_am_cost.db"), help="local database file")
    parser.add_argument("--owner-email", help="assign imported projects to this Supabase user")
    args = parser.parse_args()

    if not os.path.exists(args.sqlite):
        sys.exit(f"Local database not found: {args.sqlite}")
    data = read_local_rows(args.sqlite)

    if args.sql_out:
        write_sql(args.sql_out, data, args.owner_email)
    else:
        copy_direct(args.database_url, data, args.owner_email)


if __name__ == "__main__":
    main()
